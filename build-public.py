#!/usr/bin/env python3
# Build the brother's public index.html.
# Parts (in order): robots meta -> PIN curtain -> dashboard (with a tiny hook injected) -> Supabase live layer.
# The hook `window.__gfhIngest = applySheet;` is injected ONLY here, into the dashboard's final IIFE close,
# so the shared source file (Medi's artifact) stays byte-for-byte unchanged.

import io, os, subprocess

BASE = r"C:\Claude\Personal\Gold-Dashboard-Public"
DASH = r"C:\Claude\Personal\Project Alchemy\gold-flip-dashboard.html"

# ---------------------------------------------------------------------------
# CROSS-REPO GUARD
#
# This is the ONE place two separate workstreams touch. DASH lives in the
# Project Alchemy repo, which another Claude session edits; everything else the
# build reads lives here in Gold-Dashboard-Public. So the failure mode is
# specific and silent: run the build while that file is mid-edit and you
# publish somebody's half-finished work straight onto the brother's live page,
# with nothing on screen admitting it.
#
# Committed means "a human decided it was done". So: refuse to build from an
# uncommitted DASH. Set GFH_ALLOW_DIRTY=1 to override when you are deliberately
# testing an in-progress dashboard locally.
# ---------------------------------------------------------------------------
def _dash_uncommitted():
    try:
        r = subprocess.run(
            ["git", "-C", os.path.dirname(DASH), "status", "--porcelain", "--", os.path.basename(DASH)],
            capture_output=True, text=True, timeout=15)
        return r.stdout.strip()
    except Exception:
        return ""          # no git available -> never block the build on tooling

_dirty = _dash_uncommitted()
if _dirty and os.environ.get("GFH_ALLOW_DIRTY") != "1":
    raise SystemExit(
        "REFUSING TO BUILD - the dashboard source has uncommitted changes:\n"
        "    %s\n\n"
        "That file lives in the Project Alchemy repo and another session edits it.\n"
        "Building now would publish work someone has not finished to the live page.\n\n"
        "Do one of these:\n"
        "  1. Let the other session commit, then build again  (normal case)\n"
        "  2. GFH_ALLOW_DIRTY=1 python build-public.py        (deliberate local test)\n"
        % _dirty)

# charset MUST be in the first 1024 bytes or the browser guesses Latin-1 → mojibake (●·—✅ garble).
head   = '<!DOCTYPE html>\n<meta charset="utf-8">\n<meta name="robots" content="noindex,nofollow">\n'
pin    = io.open(os.path.join(BASE, "_pin-overlay.html"), encoding="utf-8").read()
dash   = io.open(DASH, encoding="utf-8").read()
live   = io.open(os.path.join(BASE, "_supabase-live.html"), encoding="utf-8").read()

# Hoist the Alchemy favicon block into <head>. In the source it sits right after
# <title>, but here the PIN curtain's <div> comes first and opens <body>, so left in
# place the icon links parse into body - Chrome shrugs, iPhone home-screen icons do
# not. The block itself is generated by Project Alchemy/tools/alchemy-favicon.py.
FAV_BEGIN, FAV_END = "<!-- ALCHEMY-FAVICON", "<!-- /ALCHEMY-FAVICON -->"
_a = dash.find(FAV_BEGIN)
if _a != -1:
    _b = dash.index(FAV_END, _a) + len(FAV_END)
    head += dash[_a:_b] + "\n"
    dash = dash[:_a] + dash[_b:].lstrip("\n")

# Inject the hook right before the main IIFE close in the dashboard only.
# The main IIFE closes at COLUMN 0 ("\n})();"). Nested ones are indented. On 11/16 a
# nested, indented `})();` added later in the file caught the plain rfind, the hook landed
# in a closure with no applySheet, and live prices never reached the math for a week.
marker = "\n})();"
idx = dash.rfind(marker)
if idx == -1:
    raise SystemExit("ERROR: could not find the main IIFE close (a line that is exactly `})();`).")
idx += 1
# The hook must sit in the SAME <script> as `function applySheet(`, after it.
_as = dash.rfind("function applySheet(", 0, idx)
if _as == -1 or dash.rfind("<script", _as, idx) != -1 or dash.rfind("</script>", _as, idx) != -1:
    raise SystemExit("ERROR: the hook spot is not inside the script that defines applySheet - refusing to publish a page whose live prices would never reach the math.")
hook = "\n  window.__gfhIngest = applySheet;   // public-page ingest hook (build-injected; unused in the artifact)\n"
dash_patched = dash[:idx] + hook + dash[idx:]

# Safety checks
assert "window.__gfhIngest = applySheet;" in dash_patched, "hook not injected"
assert dash_patched.count(marker) == dash.count(marker), "IIFE count changed"

# ---------------------------------------------------------------------------
# VERSION STAMP — answer "which build am I looking at?" from the page itself.
# The source footer carries a "dev copy" marker; a published build replaces it
# with the dashboard source commit + build time (UTC). If a page still says
# "dev copy", it is the raw artifact, not a build. This exists because on
# 2026-07-28 three copies of this page (source, artifact, live site) were
# compared by eye and nobody could tell which was current.
# ---------------------------------------------------------------------------
import datetime
VER_MARKER = "version: dev copy — not a published build"
if VER_MARKER not in dash_patched:
    raise SystemExit("ERROR: version marker missing from the dashboard footer.")
try:
    r = subprocess.run(["git", "-C", os.path.dirname(DASH), "rev-parse", "--short", "HEAD"],
                       capture_output=True, text=True, timeout=15)
    _commit = r.stdout.strip() or "unknown"
except Exception:
    _commit = "unknown"
_built = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
dash_patched = dash_patched.replace(
    VER_MARKER, "version: %s · built %s" % (_commit, _built), 1)

# BUILD STAMP for the live layer (2026-09-01): buyzone_history writes carry this so
# migration 011's trigger can reject rows from outdated tabs (the rival-writer fix).
STAMP_MARKER = "__GFH_BUILD_STAMP__"
if STAMP_MARKER not in live:
    raise SystemExit("ERROR: GFH build-stamp placeholder missing from _supabase-live.html.")
live = live.replace(STAMP_MARKER, "%s %s" % (_commit, _built))

out = head + pin + dash_patched + live

# ---------------------------------------------------------------------------
# BROKEN-SCRIPT GUARD (2026-11-16). The 7:53 sheet edit wrote a stray control
# byte (chr 1, a regex backreference gone wrong) after ELEM_SHEET_DATE. That one
# byte was a syntax error that killed the whole price engine: BUY froze at a
# stale $4,649.99 and the data-guard bar fired all day. Refuse to publish a page
# with control bytes, or with an inline <script> that does not parse.
# ---------------------------------------------------------------------------
import re as _re, tempfile as _tf, shutil as _sh
_CTL = "[" + chr(0) + "-" + chr(8) + chr(11) + chr(12) + chr(14) + "-" + chr(31) + chr(127) + "]"
_ctl = [(out[:m.start()].count("\n") + 1, ord(m.group())) for m in _re.finditer(_CTL, out)]
if _ctl:
    raise SystemExit("REFUSING TO PUBLISH - control bytes in the page (line, byte code): %s" % _ctl[:5])
_node = _sh.which("node")
if _node:
    _scripts = _re.finditer(r'<script(?![^>]*\bsrc=)(?![^>]*type="(?:application/json|text/template|application/ld\+json)")[^>]*>(.*?)</script>', out, _re.S)
    for _i, _m in enumerate(_scripts):
        with _tf.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as _f:
            _f.write(_m.group(1))
        _r = subprocess.run([_node, "--check", _f.name], capture_output=True, text=True)
        os.unlink(_f.name)
        if _r.returncode:
            raise SystemExit("REFUSING TO PUBLISH - inline script #%d (page line %d) does not parse:\n%s"
                             % (_i, out[:_m.start(1)].count("\n") + 1, _r.stderr[:600]))
    print("script guard: every inline script parses, no control bytes")
else:
    print("script guard: node not found - syntax check skipped")

with io.open(os.path.join(BASE, "index.html"), "w", encoding="utf-8", newline="\n") as f:
    f.write(out)

print("Built index.html: %d bytes (dash %d + pin %d + live %d)" % (len(out), len(dash), len(pin), len(live)))

# ---------------------------------------------------------------------------
# REGISTER THIS BUILD (2026-10-07, migration 024): tell the database which build is
# current so buyzone_history refuses rows from any OLDER tab. On 10/7 a one-day-old
# tab wrote a $49-high buy-zone point and the 4-day rule (022) let it through.
# Uses the management token already in the environment (same one daily_pull.py uses);
# best-effort — a failed registration is printed, never fatal, and the 4-day rule
# stays as the fallback. Skipped for dirty/test builds so they can't lock out the live one.
# ---------------------------------------------------------------------------
if os.environ.get("GFH_ALLOW_DIRTY") != "1" and _commit != "unknown":
    _tok = os.environ.get("SUPABASE_ACCESS_TOKEN", "")
    if not _tok:
        print("build register: no SUPABASE_ACCESS_TOKEN in env - skipped (4-day rule still applies)")
    else:
        try:
            import json, urllib.request
            _sql = ("insert into public.dash_build (id, build, built) values (1, %s, %s) "
                    "on conflict (id) do update set build = excluded.build, built = excluded.built, set_at = now()"
                    % ("'" + ("%s %s" % (_commit, _built)).replace("'", "''") + "'",
                       "'" + _built.replace(" UTC", "+00") + "'"))
            _req = urllib.request.Request(
                "https://api.supabase.com/v1/projects/cuubqcxzvyiryxcygadh/database/query",
                data=json.dumps({"query": _sql}).encode("utf-8"),
                headers={"Authorization": "Bearer " + _tok, "Content-Type": "application/json"})
            urllib.request.urlopen(_req, timeout=20).read()
            print("build register: dash_build = %s %s" % (_commit, _built))
        except Exception as _e:
            print("build register FAILED (%s) - 4-day rule still applies" % _e)
        # ONE home for the constants Sabz used to hand-copy (2026-10-22, migration 032):
        # parse them from the dashboard source just built and upsert alchemy_constants.
        try:
            import alchemy_constants as _ac
            _consts = _ac.parse(dash)
            _sql = ("insert into public.alchemy_constants (id, consts, build) values (1, %s::jsonb, %s) "
                    "on conflict (id) do update set consts = excluded.consts, build = excluded.build, set_at = now()"
                    % ("'" + json.dumps(_consts).replace("'", "''") + "'",
                       "'" + ("%s %s" % (_commit, _built)).replace("'", "''") + "'"))
            _req = urllib.request.Request(
                "https://api.supabase.com/v1/projects/cuubqcxzvyiryxcygadh/database/query",
                data=json.dumps({"query": _sql}).encode("utf-8"),
                headers={"Authorization": "Bearer " + _tok, "Content-Type": "application/json"})
            urllib.request.urlopen(_req, timeout=20).read()
            print("constants: pamp %s generic %s call-in %s online prem %s sheet %s cards %d" % (
                _consts["elemetal_pamp"], _consts["elemetal_generic"], _consts["call_in_bonus"],
                _consts["online_prem"], _consts["sheet_date"], len(_consts["cards"])))
        except Exception as _e:
            print("constants FAILED (%s) - Sabz keeps its fallback copies" % _e)
print("Hook injected before char offset %d (of %d)." % (idx, len(dash)))
